    /** Türkçe karakterleri sadeleştirir: "Çorba" -> "corba" */
    public static String norm(String s) {
        String t = s.toLowerCase(new Locale("tr"));
        StringBuilder b = new StringBuilder(t.length());
        for (char c : t.toCharArray()) {
            switch (c) {
                case 'ç': b.append('c'); break;
                case 'ğ': b.append('g'); break;
                case 'ı': b.append('i'); break;
                case 'ö': b.append('o'); break;
                case 'ş': b.append('s'); break;
                case 'ü': b.append('u'); break;
                case 'â': b.append('a'); break;
                case 'î': b.append('i'); break;
                case 'û': b.append('u'); break;
                default: b.append(c);
            }
        }
        return b.toString();
    }

